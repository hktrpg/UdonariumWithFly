#!/usr/bin/env node
/**
 * Writes src/environments/version.ts from the current git commit
 * (or GitHub Actions env when present).
 */
import { execSync } from 'node:child_process';
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outPath = join(root, 'src', 'environments', 'version.ts');

function git(cmd) {
  try {
    return execSync(cmd, { cwd: root, encoding: 'utf8' }).trim();
  } catch {
    return '';
  }
}

const shaFull = (process.env.GITHUB_SHA || git('git rev-parse HEAD') || 'unknown').trim();
const sha = shaFull.length >= 7 ? shaFull.slice(0, 7) : shaFull;
const branch = (
  process.env.GITHUB_HEAD_REF ||
  process.env.GITHUB_REF_NAME ||
  git('git rev-parse --abbrev-ref HEAD') ||
  'unknown'
).trim();
const date = (
  git('git log -1 --format=%cs') ||
  new Date().toISOString().slice(0, 10)
).trim();

const display = `${date} ${sha} ${branch}`;

const source = `/* Auto-generated by scripts/write-git-version.mjs - do not edit. */
export const appVersion = {
  date: ${JSON.stringify(date)},
  sha: ${JSON.stringify(sha)},
  branch: ${JSON.stringify(branch)},
  display: ${JSON.stringify(display)},
} as const;
`;

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, source, 'utf8');
console.log(`[write-git-version] ${display}`);
